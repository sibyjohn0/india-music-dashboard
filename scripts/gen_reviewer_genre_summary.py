#!/usr/bin/env python3
"""gen_reviewer_genre_summary.py — static, crawlable "browse by genre" section
for reviewers/index.html, with real counts computed from data/reviewers.json.

WHY: GSC showed /reviewers/ ranking page 1 (avg position 8.5) for genre-specific
searches like `"submit your music" "@gmail.com" "trip hop"` and
`"playlist submission" "@gmail.com" "indie folk acoustic"` with ZERO clicks,
despite being by far the highest-impression page on the site (2,265/28d). The
page's curator data is entirely client-rendered from reviewers.json, so Google
has no genre-specific text in the initial HTML to put in the search snippet —
nothing to match "indie folk acoustic" against. This script bakes real,
server-side genre counts into the page source so that text exists.

The 10 buckets and their keyword matching logic are copy-exact from the
GENRE_KEYWORDS map + matchesGenre() in reviewers/index.html's own filter JS —
if that map changes, update BUCKETS below to match, or the displayed counts
will drift from what the live filter actually returns.

Re-run whenever data/reviewers.json refreshes (wired into scripts/pipeline.py
as a reviewers-only step). Idempotent: replaces content between the
GENRE_SUMMARY marker comments only.
"""
import json, re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "data" / "reviewers.json"
TARGET = REPO / "reviewers" / "index.html"

BUCKETS = [
    ("indie",      "Indie / Alt",      ["indie", "alternative", "alt-", "indie-pop", "indie-rock", "indietronica"]),
    ("folk",       "Folk / Acoustic",  ["folk", "acoustic", "singer-songwriter", "americana", "country", "bluegrass"]),
    ("hiphop",     "Hip Hop",          ["hip-hop", "hip hop", "hiphop", "rap", "trap", "grime", "drill"]),
    ("electronic", "Electronic",       ["electronic", "edm", "dance", "techno", "house", "trance", "ambient", "synthwave", "electronica", "dubstep", "dnb", "drum-and-bass"]),
    ("rnb",        "R&amp;B / Soul",   ["r&b", "rnb", "soul", "r-n-b", "neo-soul", "funk"]),
    ("pop",        "Pop",              ["pop", "bubblegum", "synth-pop", "dream-pop"]),
    ("rock",       "Rock",             ["rock", "punk", "grunge", "post-rock", "shoegaze", "emo", "hardcore"]),
    ("lofi",       "Lo-Fi",            ["lo-fi", "lofi", "chill", "chillhop", "chillout"]),
    ("jazz",       "Jazz / Classical", ["jazz", "blues", "classical", "fusion", "bossa nova", "bossanova", "swing"]),
    ("metal",      "Metal",            ["metal", "heavy metal", "death metal", "black metal", "doom", "thrash"]),
]

def is_free(r):
    if r.get("category") != "submithub":
        return True
    return (r.get("price_credits") or 0) == 0

def compute_counts(reviewers):
    out = []
    for key, label, keywords in BUCKETS:
        total = 0
        free = 0
        for r in reviewers:
            haystack = " ".join(
                (r.get("genres") or []) + (r.get("genre_slugs") or []) + [r.get("description") or ""]
            ).lower()
            if any(k in haystack for k in keywords):
                total += 1
                if is_free(r):
                    free += 1
        out.append((key, label, total, free))
    return out

def build_html(counts):
    chips = []
    for key, label, total, free in counts:
        if total == 0:
            continue
        free_note = f", {free} free to pitch" if free else ""
        chips.append(
            f'<a href="#filter-bar" class="genre-chip" '
            f'onclick="var b=document.querySelector(\'#filter-genre [data-val=&quot;{key}&quot;]\');if(b)b.click();">'
            f'<b>{label}</b><span>{total} reviewers{free_note}</span></a>'
        )
    chips_html = "\n      ".join(chips)
    return (
        "<!-- GENRE_SUMMARY_START (generated by scripts/gen_reviewer_genre_summary.py, do not hand-edit) -->\n"
        '<div class="genre-summary">\n'
        "  <h2>Find curators and reviewers by genre</h2>\n"
        "  <p>Real counts from the database below, filtered live when you click one.</p>\n"
        '  <div class="genre-summary-grid">\n'
        f"      {chips_html}\n"
        "  </div>\n"
        "</div>\n"
        "<!-- GENRE_SUMMARY_END -->"
    )

def main():
    reviewers = json.load(open(DATA, encoding="utf-8"))["reviewers"]
    counts = compute_counts(reviewers)
    block = build_html(counts)

    html = TARGET.read_text(encoding="utf-8")
    pattern = re.compile(
        r"<!-- GENRE_SUMMARY_START.*?-->.*?<!-- GENRE_SUMMARY_END -->",
        re.S,
    )
    if pattern.search(html):
        html = pattern.sub(block, html)
    else:
        marker = '<div class="filter-bar" id="filter-bar">'
        if marker not in html:
            raise SystemExit("ERROR: could not find filter-bar marker to insert genre summary before")
        html = html.replace(marker, block + "\n" + marker, 1)

    TARGET.write_text(html, encoding="utf-8")
    print("Genre summary updated:")
    for key, label, total, free in counts:
        print(f"  {label:20s} {total:4d} total, {free:4d} free")

if __name__ == "__main__":
    main()
