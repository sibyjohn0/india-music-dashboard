#!/usr/bin/env python3
"""inject_playbook_static.py — give /playbook/ real, crawlable body text.

BUG FOUND BY HAND (2026-11-17): the playbook's actual content (44 sections,
~30,000 words) lives entirely as a JS data array (SECTIONS) in
playbook/index.html, rendered into the DOM only by client-side JS when a
reader picks a section. A non-JS fetch of the page sees ~39 words total
(title, nav, footer) -- confirmed by hand. Google renders JS so it's mostly
fine there, but AI assistants (this site's best-converting traffic channel
per GA4) often fetch raw HTML without executing JS, so they'd see next to
nothing.

This script extracts the real SECTIONS content (same data the interactive
reader uses -- single source of truth, nothing duplicated by hand) and
injects it as a genuinely-present, real HTML block early in <body>. It's
hidden ONLY when JS actually runs (an inline script adds a `js` class to
<html> before paint; a CSS rule keyed off that class hides the static
block), via the standard no-FOUC pattern -- so a real browser still gets
the existing interactive single-section reader unchanged, and a non-JS
client sees the full real content instead of a loading shell.

Run: python3 scripts/inject_playbook_static.py
Idempotent: re-running replaces the previously-injected block cleanly.
"""
import re, subprocess, json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PAGE = REPO / "playbook" / "index.html"

START_MARK = "<!-- STATIC-CONTENT-START (generated by inject_playbook_static.py, do not hand-edit) -->"
END_MARK = "<!-- STATIC-CONTENT-END -->"


def extract_sections():
    html = PAGE.read_text(encoding="utf-8")
    lines = html.split("\n")
    # Helper-function region (buildJourneyContent + its own nested helpers)
    # sits between the end of SECTIONS and the first DOM-touching function
    # (buildPhaseTabs). Everything in that span is pure, self-contained JS.
    start_idx = next(i for i, l in enumerate(lines) if l.startswith("function buildJourneyContent"))
    end_idx = next(i for i, l in enumerate(lines) if l.startswith("function buildPhaseTabs"))
    helpers = "\n".join(lines[start_idx:end_idx])

    m = re.search(r"const SECTIONS = (\[.*?\n\]); // end SECTIONS", html, re.S)
    if not m:
        raise SystemExit("Could not find SECTIONS array in playbook/index.html")

    js = helpers + "\n\nconst SECTIONS = " + m.group(1) + ";\n\nconsole.log(JSON.stringify(SECTIONS));\n"
    tmp = Path("/tmp/playbook_sections_extract.js")
    tmp.write_text(js)
    out = subprocess.run(["node", str(tmp)], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit(f"Node extraction failed:\n{out.stderr}")
    return json.loads(out.stdout)


def esc(s):
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_static_html(sections):
    parts = ['<div id="static-playbook" aria-hidden="false">',
             '<p style="color:#9a94a6;font-size:13px">The full playbook, all 44 sections. '
             'Use the interactive reader above for the phase-by-phase version with checklists.</p>']
    seen_phase = None
    for s in sections:
        if s.get("phaseName") != seen_phase:
            seen_phase = s.get("phaseName")
            parts.append(f'<h2 style="margin-top:40px">{esc(seen_phase)}</h2>')
        parts.append(f'<section id="static-{esc(s["id"])}">')
        parts.append(f'<h3>{esc(s["title"])}</h3>')
        parts.append(s.get("content", ""))  # trusted first-party HTML, not user input
        checklist = s.get("checklist")
        if isinstance(checklist, dict):
            for cat, items in checklist.items():
                if isinstance(items, list) and items:
                    parts.append(f'<h4>{esc(cat.title())}</h4><ul>')
                    parts.extend(f'<li>{esc(it)}</li>' for it in items)
                    parts.append('</ul>')
        parts.append('</section>')
    parts.append('</div>')
    return "\n".join(parts)


def main():
    sections = extract_sections()
    print(f"Extracted {len(sections)} sections")
    static_html = build_static_html(sections)
    word_count = len(re.sub(r"<[^>]+>", " ", static_html).split())
    print(f"Static block: {len(static_html):,} bytes, ~{word_count:,} words")

    html = PAGE.read_text(encoding="utf-8")

    # Replace a previously-injected block if present (idempotent re-run),
    # else insert fresh right after the primary nav.
    block = f"{START_MARK}\n{static_html}\n{END_MARK}"
    if START_MARK in html:
        html = re.sub(re.escape(START_MARK) + r".*?" + re.escape(END_MARK), block, html, flags=re.S)
    else:
        html = html.replace("</nav>\n", "</nav>\n\n" + block + "\n", 1)

    # no-FOUC toggle: add `js` to <html> before first paint; CSS hides the
    # static block only when that class is present (i.e. only when JS ran).
    if 'document.documentElement.classList.add(\'js\')' not in html:
        html = html.replace("<head>", "<head>\n<script>document.documentElement.classList.add('js')</script>", 1)
    if "#static-playbook{display:none}" not in html:
        html = html.replace("<head>",
                             "<head>\n<style>.js #static-playbook{display:none}</style>", 1)

    PAGE.write_text(html, encoding="utf-8")
    print(f"Written -> {PAGE}")


if __name__ == "__main__":
    main()
