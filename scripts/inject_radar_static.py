#!/usr/bin/env python3
"""inject_radar_static.py — keep radar.html's pre-JS summary real and current.

radar.html is a client-side app: a non-JS fetch sees only "Loading channel
data...", "Loading community conversations...", "No upcoming shows found"
placeholder text (confirmed by hand) -- Google renders JS so it mostly
copes, but AI assistants (this site's best-converting channel per GA4)
often don't execute JS. There was already a short <noscript> summary
(2 sentences, fixed text, no real numbers), added earlier as a partial fix.

This replaces it with a CSS-hidden-only-when-JS-runs static block (same
no-FOUC pattern as /playbook/ -- more robust than <noscript> against
text-extraction tools that specifically skip noscript content) carrying
real counts pulled from the same data files the page itself fetches, so
the numbers can't go stale the way the rest of this audit found elsewhere
on the site. Run daily in the pipeline so it never drifts.

Run: python3 scripts/inject_radar_static.py
Idempotent: re-running replaces the previously-injected block.
"""
import json, re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PAGE = REPO / "radar.html"
DATA = REPO / "data"

START_MARK = "<!-- STATIC-CONTENT-START (generated by inject_radar_static.py, do not hand-edit) -->"
END_MARK = "<!-- STATIC-CONTENT-END -->"


def main():
    tracked = json.loads((DATA / "tracked_artists.json").read_text())
    venues = json.loads((DATA / "venues.json").read_text())

    n_artists = tracked.get("total", 0)
    cities = list(venues.get("cities", {}).keys())
    n_shows = sum(c.get("show_count", 0) for c in venues.get("cities", {}).values())
    city_names = ", ".join(c.title() for c in cities[:-1]) + (f" and {cities[-1].title()}" if len(cities) > 1 else cities[0].title() if cities else "")

    text = (
        f"Radar tracks independent Indian musicians, live venues, and upcoming shows "
        f"across six cities, updated daily from public data. It currently tracks "
        f"{n_artists} independent artists and {n_shows} upcoming shows across "
        f"{city_names}. It surfaces which artists are breaking out week over week "
        f"and what is actually playing live right now, not a static directory."
    )

    static_html = f'<div id="static-radar" aria-hidden="false" style="max-width:760px;margin:24px auto;padding:0 24px;color:#574C63;line-height:1.6">{text}</div>'
    block = f"{START_MARK}\n{static_html}\n{END_MARK}"

    html = PAGE.read_text(encoding="utf-8")

    # Remove the old plain <noscript> version if present (superseded by the
    # CSS-toggle block below, which a non-JS text-extractor won't skip).
    html = re.sub(r'<noscript><div class="noscript-seo"[^>]*>.*?</div></noscript>\n?', '', html)

    if START_MARK in html:
        html = re.sub(re.escape(START_MARK) + r".*?" + re.escape(END_MARK), block, html, flags=re.S)
    else:
        html = html.replace("</nav>\n", "</nav>\n\n" + block + "\n", 1) if "</nav>\n" in html \
            else html.replace("<body>", "<body>\n" + block + "\n", 1)

    if "document.documentElement.classList.add('js')" not in html:
        html = html.replace("<head>", "<head>\n<script>document.documentElement.classList.add('js')</script>", 1)
    if "#static-radar{display:none}" not in html:
        html = html.replace("<head>", "<head>\n<style>.js #static-radar{display:none}</style>", 1)

    PAGE.write_text(html, encoding="utf-8")
    print(f"Written -> {PAGE}")
    print(f"  {n_artists} artists, {n_shows} shows across {len(cities)} cities")


if __name__ == "__main__":
    main()
